export type MessageKey = keyof typeof messages.en;

export function normalizeLocale(value: string | null | undefined): PlayerLocale {
  return value?.toLowerCase().startsWith("am") ? "am" : "en";
}

export function message(locale: PlayerLocale, key: MessageKey): string {
  return messages[locale][key];
}
